import type { BenchmarkReport } from "./measure";

export interface BenchmarkStamp {
	date: string;
	version: string;
}

const COMMAND = "cortex benchmark --write";

// The line that says this file is this command's to rewrite. `--write` reads it
// back before replacing anything: a BENCHMARKS.md without it belongs to someone
// else, and the date it carries is reused when nothing else moved, so a daily
// re-run does not dirty the diff on its own.
const GENERATED_PREFIX = `Generated by \`${COMMAND}\` on `;
const DATE_LENGTH = "YYYY-MM-DD".length;

// Deliberately ASCII: a table is the one place in this CLI where box drawing
// would have been tempting, and padded columns read the same in every console.
const LABEL_WIDTH = 48;
const NUMBER_WIDTH = 12;
const WRAP_WIDTH = 76;

// Cortex is what every other row is divided by, so its own ratio is one by
// construction; a null anywhere else is a run with nothing to divide by.
const BASELINE = 1;

interface Line {
	label: string;
	tokens: number;
	ratio: number | null;
}

export function formatBenchmarkTable(report: BenchmarkReport): string {
	return [
		`cortex benchmark  ${report.project}`,
		`method ${report.method.id} | ${report.questions} questions | retrieval ${report.retrieval}`,
		scaleLine(report),
		"",
		row("what the agent reads per question", ["tokens", "vs cortex"]),
		...lines(report).map((line) =>
			row(line.label, [count(line.tokens), times(line.ratio)]),
		),
		"",
		hitRateLine(report),
		...wrapped(`${report.hitRateCaveat}.`).map((line) => `  ${line}`),
	].join("\n");
}

export function formatBenchmarkMarkdown(
	report: BenchmarkReport,
	stamp: BenchmarkStamp,
): string {
	return [
		"# Benchmarks",
		"",
		"Cortex claims an economy: the agent reads the few decisions that answer",
		"its question instead of the whole record, let alone the whole repository.",
		"This is that claim, measured.",
		"",
		`${GENERATED_PREFIX}${stamp.date} with cortex ${stamp.version},`,
		`against ${report.project}.`,
		"",
		...markdownScale(report),
		"",
		...markdownTable(report),
		"",
		...wrapped(`**${hitRateLine(report)}** - ${report.hitRateCaveat}.`),
		"",
		...methodSection(report),
		"",
		...caveatsSection(report),
		"",
	].join("\n");
}

// The date a previous run stamped, and the proof that a previous run wrote this
// file at all. Null for a file this command did not generate.
export function generatedDate(markdown: string): string | null {
	const line = markdown
		.split("\n")
		.find((one) => one.startsWith(GENERATED_PREFIX));
	if (line === undefined) return null;
	return line.slice(
		GENERATED_PREFIX.length,
		GENERATED_PREFIX.length + DATE_LENGTH,
	);
}

function lines(report: BenchmarkReport): Line[] {
	return [
		{
			label: `whole decision corpus (${report.corpus.decisions} decisions)`,
			tokens: report.corpus.tokens,
			ratio: report.economy.corpusPerAnswer,
		},
		{
			label: `repository grep, median keyword (${round(report.grepMedian.meanFiles)} files)`,
			tokens: report.grepMedian.meanTokens,
			ratio: report.economy.grepMedianPerAnswer,
		},
		{
			label: `repository grep, narrowest keyword (${round(report.grepBest.meanFiles)} files)`,
			tokens: report.grepBest.meanTokens,
			ratio: report.economy.grepBestPerAnswer,
		},
		{
			label: `cortex answer (${round(report.answer.meanDecisions)} decisions)`,
			tokens: report.answer.meanTokens,
			ratio: BASELINE,
		},
	];
}

function markdownScale(report: BenchmarkReport): string[] {
	return [
		`- Corpus: ${count(report.corpus.tokens)} tokens in ${report.corpus.decisions} active decisions.`,
		`- Repository: ${count(report.repository.tokens)} tokens in ${report.repository.files} files git would not ignore.`,
		`- Retrieval: ${report.retrieval}.`,
		`- Questions: ${report.questions}.`,
	];
}

function markdownTable(report: BenchmarkReport): string[] {
	return [
		"| what the agent reads per question | tokens | vs cortex |",
		"| --- | ---: | ---: |",
		...lines(report).map(
			(line) =>
				`| ${line.label} | ${count(line.tokens)} | ${times(line.ratio)} |`,
		),
	];
}

function methodSection(report: BenchmarkReport): string[] {
	return [
		"## Method",
		"",
		`**Questions** - one per active decision, its own title, ordered by id (${report.questions} here).`,
		"A fixed list for a given corpus, and derivable in any project, where a",
		"hand-written one would only ever fit the repository it was written for.",
		"",
		"**Answer** - what `search` returns for that question, through the same path",
		"an agent takes, charged the full text of every decision file it names.",
		"",
		"**Grep baseline** - every file git would not ignore, outside `.cortex/`,",
		"containing one term of the question, case-insensitively. That is the",
		"working tree a person greps: tracked files and the untracked ones the",
		"project's own `.gitignore` does not hide. One term at a time, never their",
		"union: half the words in a question are connectives matching nearly every",
		"file, so a union would measure the stopwords. The narrowest term - the one",
		"matching the fewest files - is the floor of this alternative and the number",
		"the comparison should be judged on; the median term is what one ordinary",
		"keyword costs.",
		"",
		`**Tokens** - \`${report.method.id}\`: ${report.method.description}.`,
		"No tokenizer for the model that will read these decisions is available in",
		"process, so the count is an approximation, named here so it is never",
		"mistaken for another model's. It is calibrated against the SentencePiece",
		"tokenizer cortex already ships (embeddinggemma-300m) over this",
		"repository's markdown and TypeScript: 1.03x its total across 181 files,",
		"0.83x to 1.21x on any single file. Both sides of every ratio use the same",
		"counter, so the economy figures survive the approximation.",
	];
}

function caveatsSection(report: BenchmarkReport): string[] {
	return [
		"## What this does not measure",
		"",
		"- Answer quality. The hit rate above only asks whether a decision comes",
		"  back for its own title, which is a friendlier query than a person's.",
		"  `bun run eval:search` grades retrieval against hand-written PT/EN",
		"  paraphrases and stays the authority on recall.",
		"- The tools themselves: the MCP tool descriptions an agent carries are",
		"  paid once per session, not once per question.",
		"- A real grep session, which iterates. One pass is the floor of that",
		"  alternative, not its average.",
		`- Any corpus but this one. At ${report.corpus.decisions} decisions the ratios say as much about the`,
		"  corpus as about cortex, and they move with it - which is why the command",
		"  writes this file rather than a person keeping it up to date.",
	];
}

function scaleLine(report: BenchmarkReport): string {
	return `corpus ${count(report.corpus.tokens)} tokens in ${report.corpus.decisions} decisions | repository ${count(report.repository.tokens)} tokens in ${report.repository.files} files`;
}

function hitRateLine(report: BenchmarkReport): string {
	const hits = report.cases.filter((one) => one.hit).length;
	return `self-retrieval hit rate ${report.hitRate.toFixed(3)} (${hits}/${report.questions})`;
}

function row(label: string, cells: string[]): string {
	return `${label.padEnd(LABEL_WIDTH)}${cells.map((cell) => cell.padStart(NUMBER_WIDTH)).join("")}`;
}

function count(value: number): string {
	return Math.round(value).toLocaleString("en-US");
}

function round(value: number): string {
	return value.toFixed(1);
}

// Everything else in this file is written pre-broken, because the markdown is
// hard-wrapped so that a re-run diffs line by line. The caveat is not: it
// belongs to the report, is printed on two surfaces of different widths, and
// arrives here as one sentence.
function wrapped(text: string): string[] {
	return text.split(" ").reduce(intoLines, []);
}

function intoLines(lines: string[], word: string): string[] {
	const last = lines.at(-1);
	if (last === undefined || last.length + 1 + word.length > WRAP_WIDTH) {
		return [...lines, word];
	}
	return [...lines.slice(0, -1), `${last} ${word}`];
}

function times(ratio: number | null): string {
	if (ratio === null) return "n/a";
	return `${ratio.toFixed(1)}x`;
}
