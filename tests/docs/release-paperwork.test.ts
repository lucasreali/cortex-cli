import { beforeAll, describe, expect, test } from "bun:test";
import { existsSync } from "node:fs";
import { join } from "node:path";
import { CORTEX_VERSION } from "@/version";

const ROOT = new URL("../../", import.meta.url).pathname;

async function read(file: string): Promise<string> {
	return Bun.file(join(ROOT, file)).text();
}

let changelog = "";
let readme = "";

beforeAll(async () => {
	changelog = await read("CHANGELOG.md");
	readme = await read("README.md");
});

// v0.4.0 was tagged and then nineteen commits — five of them user-visible
// features — landed on top of it while package.json still said 0.4.0, because
// nothing anywhere had to agree with it. These are the places that now do.
describe("the version in package.json is the version everywhere", () => {
	test("the changelog has an entry for it", async () => {
		expect(changelog).toContain(`## [${CORTEX_VERSION}]`);
		expect(changelog).toContain(`[${CORTEX_VERSION}]: https://github.com/`);
	});

	test("the README pins its examples to it", async () => {
		expect(readme).toContain(`CORTEX_VERSION=v${CORTEX_VERSION}`);
		expect(readme).toContain(`asset=cortex-v${CORTEX_VERSION}-`);
	});

	// BENCHMARKS.md stamps the version that produced the numbers, so a stamp
	// from an older binary is a claim about a program that no longer exists.
	test("BENCHMARKS.md was regenerated by it", async () => {
		expect(await read("BENCHMARKS.md")).toContain(
			`with cortex ${CORTEX_VERSION}`,
		);
	});
});

describe("the files a public repository is expected to have", () => {
	test.each([
		"LICENSE",
		"CHANGELOG.md",
		"SECURITY.md",
		".github/ISSUE_TEMPLATE/config.yml",
		".github/ISSUE_TEMPLATE/bug_report.yml",
		".github/ISSUE_TEMPLATE/feature_request.yml",
	])("%s exists", (file) => {
		expect(existsSync(join(ROOT, file))).toBe(true);
	});

	test("the issue templates are valid YAML with the fields GitHub requires", async () => {
		for (const file of ["bug_report.yml", "feature_request.yml"]) {
			const template = Bun.YAML.parse(
				await read(join(".github", "ISSUE_TEMPLATE", file)),
			) as { name?: string; description?: string; body?: unknown[] };
			expect(template.name).toBeString();
			expect(template.description).toBeString();
			expect(template.body?.length).toBeGreaterThan(0);
		}
	});
});

// The globs arrived from a template with every `*` replaced by `_`, so nothing
// under them was ignored and a stray daemon log was one `git add .` from being
// committed.
describe(".gitignore", () => {
	test("ignores what its own comments say it ignores", () => {
		const ignored = Bun.spawnSync(
			["git", "check-ignore", "cortex.log", "report.1.2.3.4.json"],
			{ cwd: ROOT, stdout: "pipe", stderr: "pipe" },
		);
		expect(ignored.stdout.toString().trim().split("\n")).toEqual([
			"cortex.log",
			"report.1.2.3.4.json",
		]);
	});
});
